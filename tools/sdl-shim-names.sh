#!/usr/bin/env bash
# Writes the export list of the guest's libSDL3.so.0 shim, generated from the
# game's own libSDL3.so.0, so that the shim exports exactly what the game's SDL
# does, whatever its version: target/guest-shims/libSDL3_names.h, an X-macro of
# `X(name, index)` entries in table order.
#
#   tools/sdl-shim-names.sh [game_dir]
#
# The default game directory is CS2METAL_GAME_DIR, else ~/cs2metal-kit/cs2-linux.
set -euo pipefail

root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
game="${1:-${CS2METAL_GAME_DIR:-$HOME/cs2metal-kit/cs2-linux}}"
library="$game/game/bin/linuxsteamrt64/libSDL3.so.0"
out="$root/target/guest-shims/libSDL3_names.h"

[[ -f "$library" ]] || { echo "sdl-shim-names: no libSDL3.so.0 at $library" >&2; exit 1; }
mkdir -p "$(dirname "$out")"
{
    echo "/* Generated by tools/sdl-shim-names.sh from the game's libSDL3.so.0. */"
    echo "#define SDL_SHIM_NAMES(X) \\"
    objdump -T "$library" | awk '$4 == ".text" && $NF ~ /^SDL_/ { print $NF }' | LC_ALL=C sort -u |
        awk '{ printf "    X(%s, %d) \\\n", $1, NR - 1 }'
    echo
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "sdl-shim-names: $(grep -c '    X(' "$out") names written to target/guest-shims/"
