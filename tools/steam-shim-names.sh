#!/usr/bin/env bash
# Writes the export list of the guest's steamclient.so shim, generated from the
# owner's own macOS Steam client library, so that no list of Valve's exports is
# tracked: target/guest-shims/steamclient_names.h, an X-macro of
# `X(name, index)` entries in table order. The shim exports every function the
# macOS library exports (its x86-64 slice, the one loaded under Rosetta 2), then
# the three the game's libsteam_api.so also looks up, which the host answers.
#
#   tools/steam-shim-names.sh [path/to/steamclient.dylib]
#
# The default path is the one the bridge loads (see CS2METAL_STEAMCLIENT).
set -euo pipefail

root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
default="$HOME/Library/Application Support/Steam/Steam.AppBundle/Steam/Contents/MacOS/steamclient.dylib"
library="${1:-${CS2METAL_STEAMCLIENT:-$default}}"
out="$root/target/guest-shims/steamclient_names.h"

[[ -f "$library" ]] || { echo "steam-shim-names: no Steam client library at $library" >&2; exit 1; }
mkdir -p "$(dirname "$out")"
{
    echo "/* Generated by tools/steam-shim-names.sh from the owner's Steam client library. */"
    echo "#define STEAM_SHIM_NAMES(X) \\"
    {
        nm -gU -arch x86_64 "$library" | awk '$2 == "T" { print substr($3, 2) }' | LC_ALL=C sort
        printf '%s\n' Steam_IsKnownInterface Steam_NotifyMissingInterface Breakpad_SteamSendMiniDump
    } | awk '{ printf "    X(%s, %d) \\\n", $1, NR - 1 }'
    echo
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "steam-shim-names: $(grep -c '    X(' "$out") names written to target/guest-shims/"
