use std::collections::BTreeMap;
use std::fmt::Write;

use crate::{Entry, FsAccess, ModuleScan, Seed};

fn merge(total: &mut BTreeMap<FsAccess, u64>, part: &BTreeMap<FsAccess, u64>) {
    for (kind, n) in part {
        *total.entry(*kind).or_default() += n;
    }
}

fn add(total: &mut ModuleScan, m: &ModuleScan) {
    total.code_bytes += m.code_bytes;
    total.covered_bytes += m.covered_bytes;
    total.functions += m.functions;
    merge(&mut total.fs_accesses, &m.fs_accesses);
    total.rewritable += m.rewritable;
    merge(&mut total.uncovered_fs, &m.uncovered_fs);
    merge(&mut total.data_fs, &m.data_fs);
    total.decode_failures += m.decode_failures;

    let (t, d) = (&mut total.discovery, &m.discovery);
    for (seed, n) in &d.seeds {
        *t.seeds.entry(*seed).or_default() += n;
    }
    t.reached_bytes += d.reached_bytes;
    t.instructions += d.instructions;
    merge(&mut t.fs_accesses, &d.fs_accesses);
    t.rewritable += d.rewritable;
    t.conflicts += d.conflicts;
    t.invalid += d.invalid;
    t.noreturn_calls += d.noreturn_calls;
    t.rejected += d.rejected;
    t.rejected_bytes += d.rejected_bytes;
}

fn percent(part: u64, whole: u64) -> String {
    if whole == 0 {
        "100.0%".to_owned()
    } else {
        format!("{:.1}%", 100.0 * part as f64 / whole as f64)
    }
}

/// `0`, or the non-zero counts by kind, such as `fs:0 10, fs:0x28 3`.
fn by_kind(counts: &BTreeMap<FsAccess, u64>) -> String {
    let parts: Vec<String> = FsAccess::ALL
        .iter()
        .filter_map(|k| {
            counts
                .get(k)
                .filter(|&&n| n > 0)
                .map(|n| format!("{} {n}", k.label()))
        })
        .collect();
    if parts.is_empty() {
        "0".to_owned()
    } else {
        parts.join(", ")
    }
}

/// Renders a scan as Markdown. Paths are relative to the scanned root.
pub fn markdown(entries: &[Entry]) -> String {
    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(w, "# Code scan: fs accesses, code coverage, TLS models\n");
    let _ = writeln!(
        w,
        "Generated by `cs2metal tls scan` from local files. When the files are Valve's, \
         keep this report in `reports/` and never commit it.\n"
    );

    let mut total = ModuleScan::default();
    let mut clean = 0;
    let mut bounded = 0;
    let scanned: Vec<(&str, &ModuleScan)> = entries
        .iter()
        .filter_map(|e| e.result.as_ref().ok().map(|m| (e.path.as_str(), m)))
        .collect();
    for (_, m) in &scanned {
        add(&mut total, m);
        clean += usize::from(m.rewrite_is_clean());
        bounded += usize::from(m.code_from_sections);
    }
    let d = &total.discovery;

    let _ = writeln!(w, "## Summary\n");
    let _ = writeln!(w, "| Measure | Value |\n| --- | --- |");
    let rows: Vec<(&str, String)> = vec![
        ("Modules scanned", scanned.len().to_string()),
        (
            "Modules that failed to parse",
            (entries.len() - scanned.len()).to_string(),
        ),
        ("Modules whose rewrite is clean", clean.to_string()),
        (
            "Modules whose code the section table bounds",
            bounded.to_string(),
        ),
        ("Code bytes", total.code_bytes.to_string()),
        (
            "Described by unwind tables",
            percent(total.covered_bytes, total.code_bytes),
        ),
        (
            "Reached by discovery beyond them",
            percent(d.reached_bytes, total.code_bytes),
        ),
        ("`fs` in unwind-described code", by_kind(&total.fs_accesses)),
        ("Of those, prefix located", total.rewritable.to_string()),
        ("`fs` in discovered code", by_kind(&d.fs_accesses)),
        ("Of those, prefix located", d.rewritable.to_string()),
        (
            "`fs` decodes in data that code loads by address",
            by_kind(&total.data_fs),
        ),
        ("`fs` decodes unexplained", by_kind(&total.uncovered_fs)),
        (
            "Decoder failures in unwind-described code",
            total.decode_failures.to_string(),
        ),
        (
            "Conflicts and invalid encodings on trusted paths",
            format!("{} and {}", d.conflicts, d.invalid),
        ),
        (
            "`lea` targets discarded as data",
            format!("{} ({} bytes)", d.rejected, d.rejected_bytes),
        ),
        (
            "Calls not followed past (noreturn)",
            d.noreturn_calls.to_string(),
        ),
    ];
    for (measure, value) in rows {
        let _ = writeln!(w, "| {measure} | {value} |");
    }
    let _ = writeln!(w, "\nDiscovery seeds that led into unexplored code:\n");
    let _ = writeln!(w, "| Seed | Count |\n| --- | --- |");
    for seed in Seed::ALL {
        let n = d.seeds.get(&seed).copied().unwrap_or(0);
        let _ = writeln!(w, "| {} | {n} |", seed.label());
    }

    let _ = writeln!(w, "\n## Modules\n");
    let _ = writeln!(
        w,
        "| Module | Code KB | Bounds | Unwind | Discovered | fs in unwind code | fs discovered | fs in data | fs unexplained | Bad | TLS | Clean |"
    );
    let _ = writeln!(
        w,
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
    );
    for (path, m) in &scanned {
        let _ = writeln!(
            w,
            "| `{path}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            m.code_bytes / 1024,
            if m.code_from_sections {
                "sections"
            } else {
                "segments"
            },
            percent(m.covered_bytes, m.code_bytes),
            percent(m.discovery.reached_bytes, m.code_bytes),
            by_kind(&m.fs_accesses),
            by_kind(&m.discovery.fs_accesses),
            by_kind(&m.data_fs),
            by_kind(&m.uncovered_fs),
            m.decode_failures,
            m.tls_summary().join(", "),
            if m.rewrite_is_clean() {
                "yes"
            } else {
                "**no**"
            },
        );
    }
    let failures: Vec<_> = entries
        .iter()
        .filter_map(|e| e.result.as_ref().err().map(|r| (&e.path, r)))
        .collect();
    let problems: Vec<_> = scanned
        .iter()
        .flat_map(|(p, m)| {
            let unwind = m.unwind_error.as_ref().map(|e| (p, e));
            let sections = m.section_error.as_ref().map(|e| (p, e));
            unwind.into_iter().chain(sections)
        })
        .collect();
    if !failures.is_empty() || !problems.is_empty() {
        let _ = writeln!(w, "\n## Problems\n");
        for (path, reason) in failures {
            let _ = writeln!(w, "- `{path}`: {reason}");
        }
        for (path, reason) in problems {
            let _ = writeln!(w, "- `{path}`: {reason}");
        }
    }
    out
}
